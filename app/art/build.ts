// Rebuild with: bun apps/night-stall/art/build.ts /path/to/shapeshift-labs-ink-studio
// Ink Studio revision a7e8eacb2795c39cbc29cce5ff1e805ebeb13d52 (the revision pixel-dioramas pins).
//
// Writes two kinds of file into ../views:
//   engine.ts        Ink Studio's toolkit and WebGL renderer with the scene's own code, minified, as one module.
//   world-*.ts       the scene sculpted and baked here (about half a minute), its big arrays packed small.
// The view takes the world out of store, so a window opens without sculpting anything.
import { createRequire } from "node:module";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { gzipSync } from "node:zlib";

const ink = resolve(process.argv[2] ?? "");
const require = createRequire(import.meta.url);
const studio = require(join(ink, "index.js"));
const here = import.meta.dir, views = join(here, "..", "views");

// The baked world. `squeeze` lays each array out a byte of every number at a time and a column at a time, then gzips.
const scene = require(join(here, "scene.cjs"));
const started = Date.now(), { plain, arrays } = scene.pack(studio.load());
const strides: Record<string, number> = { data: 16, pix: 8, materialIds: 1, normals: 3 };
const layout: { name: string; type: string; length: number; stride: number }[] = [], chunks: Uint8Array[] = [];
for (const [name, array] of Object.entries(arrays) as [string, Float32Array][]) {
  const stride = strides[name]!, rows = array.length / stride, width = array.BYTES_PER_ELEMENT;
  const from = new Uint8Array(array.buffer, array.byteOffset, array.byteLength), to = new Uint8Array(from.length);
  for (let b = 0; b < width; b++) for (let k = 0; k < stride; k++)
    for (let i = 0, at = (b * stride + k) * rows, read = k * width + b; i < rows; i++, read += stride * width) to[at + i] = from[read]!;
  layout.push({ name, type: array.constructor.name, length: array.length, stride });
  chunks.push(to);
}
const packed = gzipSync(Buffer.concat(chunks), { level: 9 }).toString("base64");
const PART = 6 * 1024 * 1024, parts = Math.ceil(packed.length / PART);
for (let i = 0; i < 8; i++) rmSync(join(views, `world-${i}.ts`), { force: true });
for (let i = 0; i < parts; i++)
  writeFileSync(join(views, `world-${i}.ts`), `// Generated by ../art/build.ts: part ${i + 1} of ${parts} of the baked night stall.\nexport default "${packed.slice(i * PART, (i + 1) * PART)}";\n`);
writeFileSync(join(views, "world.ts"),
  `// Generated by ../art/build.ts from art/scene.cjs with Ink Studio.\n` +
  Array.from({ length: parts }, (_, i) => `import part${i} from "./world-${i}.ts";\n`).join("") +
  `export const plain: any = JSON.parse(${JSON.stringify(JSON.stringify(plain))});\nexport const layout = ${JSON.stringify(layout)};\nexport const packed = ${Array.from({ length: parts }, (_, i) => `part${i}`).join(" + ")};\n`);
console.log(`baked in ${((Date.now() - started) / 1000).toFixed(0)} s: ${plain.world.count} splats, ${(packed.length / 1048576).toFixed(1)} MB in ${parts} parts`);

// The engine. The toolkit is plain scripts that share one scope: wrapped in a function, it hands back its names.
const scratch = mkdtempSync(join(tmpdir(), "night-stall-"));
const names = studio.EXPORTS.split(",").map((n: string) => n.trim());
// (each file also offers itself to Node's require, behind a check that the browser never passes: the bundler is not to follow it)
const toolkitText = studio.bundle().replace(/\brequire\(/g, "absent(");
writeFileSync(join(scratch, "toolkit.js"), `const absent = name => { throw new Error("Ink Studio piece missing: " + name); };\nexport default function toolkit() {\n${toolkitText}\nreturn { ${names.map((n: string) => `${n}: typeof ${n} === "undefined" ? undefined : ${n}`).join(", ")} };\n}\n`);
writeFileSync(join(scratch, "entry.js"), `import toolkit from "./toolkit.js";
import { createRenderer } from ${JSON.stringify(join(ink, "src/webgl/renderer.mjs"))};
import scene from ${JSON.stringify(join(here, "scene.cjs"))};
export { toolkit, createRenderer, scene };
`);
const out = await Bun.build({ entrypoints: [join(scratch, "entry.js")], target: "browser", format: "esm", minify: true });
if (!out.success) throw new AggregateError(out.logs, "engine build failed");
const licence = readFileSync(join(ink, "LICENSE"), "utf8").trim();
const engine = `// @ts-nocheck\n/*! Ink Studio ${studio.version}, https://github.com/siliconjungle/shapeshift-labs-ink-studio\n\n${licence}\n*/\n` +
  `/*! The night stall scene: https://github.com/cola5939/pixel-dioramas */\n// Generated by ../art/build.ts. Do not edit.\n` + await out.outputs[0]!.text();
writeFileSync(join(views, "engine.ts"), engine);
rmSync(scratch, { recursive: true, force: true });
console.log(`engine: ${(engine.length / 1048576).toFixed(2)} MB`);
